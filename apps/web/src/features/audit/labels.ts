/** Where a record can be opened, when it has a page. */
export function linkOf(entity: string, id: string): string | null {
  if (entity === 'shipment') return `/shipments/${id}`;
  if (entity === 'shipment_account') return `/shipment-accounts/${id}`;
  if (entity === 'money_account') return `/treasury/${id}`;
  return null;
}

